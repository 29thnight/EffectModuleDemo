/**
 * 표본 240개 = 60fps에서 4초.
 * 더 짧으면 GC 한 번에 p95가 통째로 흔들리고, 더 길면 부하를 바꿨을 때 숫자가 늦게 따라온다.
 */
export const SAMPLE_CAPACITY = 240

/** 보고할 백분위. p99는 표본 240개에서 상위 2~3개로 결정되어 노이즈에 너무 민감하다. */
export const REPORT_PERCENTILE = 0.95

/**
 * 부하 단계. "동시에 살아있는 파티클 수"다.
 * 2배씩 올린다. 선형 증가는 병목이 꺾이는 지점을 놓치기 쉽고,
 * 배수 증가는 로그 축에서 기울기(= 비용이 선형인지 제곱인지)를 바로 읽게 해준다.
 * 상한 2,048,000의 근거는 "여기까지 올려야 꺾인다"는 실측 기울기다.
 * 원래 상한 32,000에서는 CPU 적분이 0.407ms(예산의 2.4%)뿐이라 스윕이 vsync 고정만 보고했고,
 * 256,000까지 올려도 RTX 2080 Ti / 4070 Ti급에서는 60fps가 유지된다는 보고를 받았다.
 *
 * 헤드리스 벤치에서 잰 CPU 적분 비용은 파티클 1,000개당 약 13.7us로 생존 수에 선형이다
 * (256,000에서 3.466ms). 이 기울기를 연장하면
 *
 *   1,024,000 -> 약 14ms  (60fps 예산 16.67ms의 84%)
 *   2,048,000 -> 약 28ms  (예산 초과 — CPU만으로 60fps가 깨진다)
 *
 * 즉 GPU가 아무리 빨라도 2,048,000에서는 반드시 꺾인다. 상한을 여기에 두면
 * "한계를 못 찾았다"로 끝나는 스윕이 나오지 않는다.
 *
 * 이 구간에서 병목이 GPU가 아니라 CPU로 넘어가는 것 자체가 결과다 —
 * README 8절이 말하는 "GPU 적분(TransformFeedback) 전환"의 근거가 여기서 생긴다.
 *
 * capacity 5,120,000이 이 상한을 받치는 값이다 — 둘은 같이 움직여야 한다.
 */
export const LOAD_STEPS: readonly number[] = [
  0, 500, 1_000, 2_000, 4_000, 8_000, 16_000, 32_000, 64_000, 128_000, 256_000, 512_000, 1_024_000,
  2_048_000,
]

/** 초기 부하 단계 인덱스 (2,000개). 어지간한 노트북에서 여유 있게 60fps가 나오는 지점. */
export const DEFAULT_LOAD_INDEX = 3

/**
 * 단계마다 워밍업 1.5초.
 * 이유가 두 개다. (1) 정상 상태 도달: 수명 0.9초짜리 이펙트가 생성/소멸 균형에 이르려면
 * 최소 수명 1회분이 필요하다. (2) 셰이더 컴파일과 첫 버퍼 업로드는 단계 1에서만 발생하는데,
 * 그걸 측정에 넣으면 첫 단계만 부당하게 느리게 나온다.
 */
export const WARMUP_SECONDS = 1.5

/** 단계마다 측정 3초 = 60fps에서 약 180 프레임. 표본 링(240)을 넘지 않아 전 구간이 통계에 들어간다. */
export const MEASURE_SECONDS = 3

/**
 * vsync 고정 판정 임계값.
 *
 * 프레임 타임이 거의 흔들리지 않으면서(p95가 avg의 1.05배 이내) CPU가 그 안에 넉넉히
 * 들어가면(프레임의 40% 미만), GPU가 포화된 것이 아니라 화면 주사율을 기다리는 중이다.
 * 이 둘을 구분하지 못하면 "60fps 나왔으니 됐다"와 "한계를 아직 못 찾았다"를 같은 말로 읽게 된다.
 */
export const VSYNC_FLATNESS_RATIO = 1.05
export const VSYNC_CPU_HEADROOM_RATIO = 0.4

/**
 * 목표 도달 판정 하한. 실측 생존이 목표 N의 이 비율에 못 미치면 그 단계는 비교 대상에서 뺀다.
 *
 * 상한을 256,000까지 올리면서 생긴 실패 모드다. 부하가 걸려 프레임이 길어지면 dt 클램프
 * (MAX_DT_SECONDS = 0.1s)가 시뮬레이션 진행을 프레임당 0.1초로 묶는데, 프레임 자체가 그보다
 * 훨씬 길어지면 정상 상태에 도달하기 전에 측정 구간이 끝난다. 실제로 256,000 단계에서
 * 생존이 29,488에 머무는 것을 확인했다.
 *
 * 이때 기록되는 프레임 타임은 "동시 256,000개의 성능"이 아니라 "29,488개의 성능"이다.
 * 그걸 목표 N 라벨로 표에 올리면 남이 재현할 수 없는 숫자가 되므로, 판정에서 먼저 걸러낸다.
 *
 * 0.8인 이유: 정상 단계도 지터와 워밍업 잔여 때문에 목표의 99%에 딱 붙지는 않는다
 * (헤드리스 벤치 실측 99.0~99.1%). 0.8이면 그 자연 오차는 통과시키고 도달 실패만 잡는다.
 */
export const TARGET_REACHED_RATIO = 0.8

/** 스윕이 끝난 뒤 되돌릴 부하 단계 인덱스. */
export const SWEEP_RESTORE_INDEX = DEFAULT_LOAD_INDEX
